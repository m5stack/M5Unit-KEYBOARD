char hidUsageToChar(const uint8_t keycode, const uint8_t modifier)
{
    if (keycode >= 128) return 0;
    const bool shift = (modifier & HID_MOD_SHIFT_MASK) != 0;
    return shift ? SHIFTED_US[keycode] : UNSHIFTED_US[keycode];
}

bool isPrintableHidKey(const uint8_t keycode, const uint8_t modifier)
{
    const char c = hidUsageToChar(keycode, modifier);
    return (c != 0) && std::isprint(static_cast<unsigned char>(c));
}

